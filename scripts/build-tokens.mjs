#!/usr/bin/env node
/**
 * Pance token build — zero dependencies.
 *
 *   tokens/primitives.json ┐
 *   tokens/semantic.json   ├─▶ src/styles/tokens.css   CSS custom properties (--pance-*), aliases kept as var()
 *   tokens/components.json ┘   src/styles/theme.css    Tailwind v4 @theme mapping (bg-brand-600, text-ink…)
 *                              src/tokens.ts           Fully resolved values for JS (charts, canvas, tests)
 *                              tokens/dist/tokens.json Flat, resolved — for Figma plugins / other platforms
 *
 * Tokens follow the W3C Design Tokens Community Group format ($value / $type / $description).
 * Aliases use {path.to.token}. Run with `npm run tokens`.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const read = (f) => JSON.parse(readFileSync(resolve(root, f), 'utf8'))
const write = (f, s) => {
  const p = resolve(root, f)
  mkdirSync(dirname(p), { recursive: true })
  writeFileSync(p, s)
  console.log('  ✓', f)
}

const TIERS = ['primitives', 'semantic', 'components']
const sources = Object.fromEntries(TIERS.map((t) => [t, read(`tokens/${t}.json`)]))

/* ── Flatten every tier into one map: path → { value, type, tier, description } ── */
const tokens = new Map()
function walk(node, path, inheritedType, tier) {
  const type = node.$type ?? inheritedType
  if ('$value' in node) {
    const key = path.join('.')
    if (tokens.has(key)) throw new Error(`Duplicate token "${key}" (${tokens.get(key).tier} and ${tier})`)
    tokens.set(key, { path, value: node.$value, type, tier, description: node.$description, dark: node.$extensions?.['pance.modes']?.dark })
    return
  }
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$') || typeof v !== 'object' || v === null) continue
    walk(v, [...path, k], type, tier)
  }
}
for (const t of TIERS) walk(sources[t], [], undefined, t)

/* ── Alias helpers ── */
const REF = /^\{([^}]+)\}$/
const REF_G = /\{([^}]+)\}/g
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
const cssName = (path) => `--pance-${kebab(Array.isArray(path) ? path.join('-') : path.replace(/\./g, '-'))}`
function target(ref, from) {
  const t = tokens.get(ref)
  if (!t) throw new Error(`Unresolved alias {${ref}} in ${from}`)
  return t
}
function resolveValue(value, from, seen = new Set()) {
  if (typeof value === 'string') {
    const m = value.match(REF)
    if (m) {
      if (seen.has(m[1])) throw new Error(`Circular alias at ${from}`)
      return resolveValue(target(m[1], from).value, m[1], new Set([...seen, m[1]]))
    }
    return value.replace(REF_G, (_, r) => String(resolveValue(`{${r}}`, from, seen)))
  }
  if (Array.isArray(value)) return value.map((v) => resolveValue(v, from, seen))
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolveValue(v, from, seen)]))
  return value
}
/* Type of the token at the end of an alias chain */
const finalType = (tok) => {
  const m = typeof tok.value === 'string' && tok.value.match(REF)
  return m ? finalType(target(m[1], tok.path.join('.'))) : tok.type
}

/* ── Value → CSS (aliases become var() so the chain stays live in the browser) ── */
const cssRef = (v) => (typeof v === 'string' ? v.replace(REF_G, (_, r) => `var(${cssName(r)})`) : v)
const fontStack = (arr) => arr.map((f) => (/\s/.test(f) && !/^ui-|^system-ui$/.test(f) ? `'${f}'` : f)).join(', ')
function shadowCss(layers) {
  if (!layers.length) return 'none'
  return layers.map((l) => `${l.inset ? 'inset ' : ''}${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${cssRef(l.color)}`).join(', ')
}
function toCss(tok) {
  const { value, type } = tok
  if (typeof value === 'string' && REF.test(value)) return cssRef(value)
  switch (type) {
    case 'fontFamily': return Array.isArray(value) ? fontStack(value) : value
    case 'cubicBezier': return `cubic-bezier(${value.join(', ')})`
    case 'shadow': return shadowCss(Array.isArray(value) ? value : [value])
    case 'transition': return `${cssRef(value.duration)} ${cssRef(value.timingFunction)} ${cssRef(value.delay ?? '0ms')}`
    default: return cssRef(String(value))
  }
}
const TYPO_PARTS = { fontFamily: 'font-family', fontSize: 'font-size', fontWeight: 'font-weight', lineHeight: 'line-height', letterSpacing: 'letter-spacing' }

/* ── tokens.css ── */
const header = (what) => `/* ${what}\n   AUTO-GENERATED by scripts/build-tokens.mjs from tokens/*.json — do not edit by hand. */\n`
let css = header('Pance design tokens — CSS custom properties')
for (const tier of TIERS) {
  css += `\n/* ── ${tier} ${'─'.repeat(60 - tier.length)} */\n:root {\n`
  for (const tok of tokens.values()) {
    if (tok.tier !== tier) continue
    const name = cssName(tok.path)
    const ft = finalType(tok)
    if (ft === 'typography') {
      const m = typeof tok.value === 'string' && tok.value.match(REF)
      for (const [k, part] of Object.entries(TYPO_PARTS)) {
        const v = m ? `var(${cssName(m[1])}-${part})` : cssRef(String(tok.value[k]))
        css += `  ${name}-${part}: ${v};\n`
      }
      continue
    }
    css += `  ${name}: ${toCss(tok)};\n`
  }
  css += '}\n'
}
const darkToks = [...tokens.values()].filter((t) => t.dark !== undefined)
css += `\n/* ── dark (draft, opt-in with data-theme="dark" — ships in v1.1) ${'─'.repeat(8)} */\n:root[data-theme='dark'] {\n`
for (const tok of darkToks) css += `  ${cssName(tok.path)}: ${cssRef(String(tok.dark))};\n`
css += '}\n'
write('src/styles/tokens.css', css)

/* ── theme.css (Tailwind v4) ── */
const STEPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950']
const PALETTES = { brand: 'aqua', slate: 'slate', emerald: 'emerald', sky: 'sky', amber: 'amber', violet: 'violet', rose: 'rose' }
let theme = header('Pance → Tailwind v4 theme. Maps tokens onto the utility names the components use')
theme += '@theme {\n'
theme += '  /* Type families */\n'
theme += `  --font-display: var(${cssName('fontFamily.jakarta')});\n  --font-sans: var(${cssName('fontFamily.inter')});\n  --font-mono: var(${cssName('fontFamily.jetbrains')});\n`
for (const [tw, prim] of Object.entries(PALETTES)) {
  theme += `\n  /* ${tw}-* → color.${prim} */\n`
  for (const s of STEPS) theme += `  --color-${tw}-${s}: var(${cssName(`color.${prim}.${s}`)});\n`
}
const ALIASES = {
  ground: 'color.bg.page', canvas: 'color.bg.sunken', surface: 'color.bg.surface',
  ink: 'color.fg.default', 'ink-soft': 'color.fg.soft', 'ink-muted': 'color.fg.muted', 'ink-subtle': 'color.fg.subtle',
  line: 'color.border.default', 'line-soft': 'color.border.soft',
  'river-900': 'color.river.900', 'river-950': 'color.river.950',
  danger: 'color.intent.danger.fg', 'danger-soft': 'color.intent.danger.soft',
  success: 'color.intent.success.fg', warning: 'color.intent.warning.fg',
  info: 'color.intent.info.fg', help: 'color.intent.help.fg',
}
theme += '\n  /* Semantic surface / text / line aliases */\n'
for (const [tw, path] of Object.entries(ALIASES)) { target(path, 'theme'); theme += `  --color-${tw}: var(${cssName(path)});\n` }
const SHADOWS = { raised: 'shadow.xs', card: 'shadow.sm', popover: 'shadow.md', modal: 'shadow.lg', brand: 'shadow.brand', menu: 'shadow.menu', toast: 'shadow.toast' }
theme += '\n  /* Elevation utilities: shadow-raised, shadow-card, shadow-popover, shadow-modal, shadow-brand… */\n'
for (const [tw, path] of Object.entries(SHADOWS)) { target(path, 'theme'); theme += `  --shadow-${tw}: var(${cssName(path)});\n` }
theme += '\n  /* Radius utilities: rounded-control (12px), rounded-container (16px), rounded-item (8px) */\n'
theme += `  --radius-item: var(${cssName('radius.item')});\n  --radius-control: var(${cssName('radius.md')});\n  --radius-container: var(${cssName('radius.lg')});\n`
theme += '}\n'
write('src/styles/theme.css', theme)

/* ── Resolved outputs ── */
const resolved = {}
for (const [key, tok] of tokens) {
  let v = resolveValue(tok.value, key)
  const ft = finalType(tok)
  if (ft === 'shadow') v = shadowCss(Array.isArray(v) ? v : [v])
  else if (ft === 'cubicBezier') v = `cubic-bezier(${v.join(', ')})`
  else if (ft === 'fontFamily' && Array.isArray(v)) v = fontStack(v)
  else if (ft === 'transition') v = `${v.duration} ${v.timingFunction} ${v.delay ?? '0ms'}`
  resolved[key] = v
}
/* Nested object for TS */
const nested = {}
for (const [key, v] of Object.entries(resolved)) {
  const parts = key.split('.')
  let o = nested
  parts.slice(0, -1).forEach((p) => (o = o[p] ??= {}))
  o[parts.at(-1)] = v
}
write('src/tokens.ts', `${header('Pance design tokens — resolved values for JavaScript').replace('/*', '/**')}\nexport const tokens = ${JSON.stringify(nested, null, 2)} as const\n\nexport type PanceTokens = typeof tokens\nexport default tokens\n`)
write('tokens/dist/tokens.json', JSON.stringify(resolved, null, 2) + '\n')

/* ── docs/tokens.md — human-readable reference ── */
const esc = (s) => String(s).replace(/\|/g, '\\|')
const show = (v) => (typeof v === 'object' ? Object.entries(v).map(([k, x]) => `${k}: ${x}`).join('<br>') : v)
const swatch = (v) => (typeof v === 'string' && /^#[0-9a-f]{6}$/i.test(v) ? `![](https://placehold.co/14x14/${v.slice(1)}/${v.slice(1)}.png) ` : '')
const TIER_INTRO = {
  primitives: 'Raw values. Never referenced directly by product code — only by semantic and component tokens.',
  semantic: 'Purpose-based aliases (surface, text, intent, elevation, typography roles). Use these in product code.',
  components: 'Per-component decisions, aliased to semantic or primitive tokens.',
}
let md = `<!-- AUTO-GENERATED by scripts/build-tokens.mjs — do not edit by hand. -->\n# Token reference\n\n`
md += `${tokens.size} tokens across three tiers. Source of truth: [\`/tokens\`](../tokens). CSS variable = \`--pance-\` + the path in kebab-case (e.g. \`color.intent.primary.solid\` → \`--pance-color-intent-primary-solid\`).\n\n`
for (const tier of TIERS) {
  md += `## ${tier[0].toUpperCase() + tier.slice(1)}\n\n${TIER_INTRO[tier]}\n\n`
  const groups = new Map()
  for (const tok of tokens.values()) {
    if (tok.tier !== tier) continue
    const g = tok.path.length > 2 && ['color', 'button', 'badge'].includes(tok.path[0]) ? tok.path.slice(0, 2).join('.') : tok.path[0]
    if (!groups.has(g)) groups.set(g, [])
    groups.get(g).push(tok)
  }
  for (const [g, list] of groups) {
    md += `### \`${g}\`\n\n| Token | Value | Resolved | Dark (draft) | Notes |\n|---|---|---|---|---|\n`
    for (const tok of list) {
      const key = tok.path.join('.')
      const raw = typeof tok.value === 'string' ? tok.value : JSON.stringify(tok.value).length > 80 ? '_composite_' : JSON.stringify(tok.value)
      const r = resolved[key]
      const dk = tok.dark !== undefined ? resolveValue(tok.dark, key) : ''
      md += `| \`${key}\` | ${esc(raw)} | ${swatch(r)}${esc(show(r))} | ${dk ? swatch(dk) + esc(dk) : ''} | ${esc(tok.description ?? '')} |\n`
    }
    md += '\n'
  }
}
write('docs/tokens.md', md)

const counts = TIERS.map((t) => `${t}: ${[...tokens.values()].filter((x) => x.tier === t).length}`).join(' · ')
console.log(`\n  ${tokens.size} tokens (${counts})`)
